-- 1. BẢNG STRATEGY_CONFIGS: Lưu trữ thông tin và phiên bản cấu hình chiến lược
BEGIN
    EXECUTE IMMEDIATE '
    CREATE TABLE STRATEGY_CONFIGS (
        CONFIG_ID       VARCHAR2(64) PRIMARY KEY,
        STRATEGY_NAME   VARCHAR2(100) NOT NULL,
        VERSION         VARCHAR2(20) DEFAULT ''1.0.0'',
        PARAMETERS_JSON CLOB NOT NULL,
        DESCRIPTION     VARCHAR2(500),
        CREATED_AT      TIMESTAMP DEFAULT CURRENT_TIMESTAMP
    )';
    DBMS_OUTPUT.PUT_LINE('Table STRATEGY_CONFIGS created.');
EXCEPTION
    WHEN OTHERS THEN IF SQLCODE = -955 THEN NULL; ELSE RAISE; END IF;
END;
/

-- 2. BẢNG BACKTEST_RUNS: Nhật ký đợt kiểm thử
BEGIN
    EXECUTE IMMEDIATE '
    CREATE TABLE BACKTEST_RUNS (
        RUN_ID          VARCHAR2(64) PRIMARY KEY,
        CONFIG_ID       VARCHAR2(64),
        START_DATE      DATE,
        END_DATE        DATE,
        INITIAL_CAPITAL NUMBER(18, 2) NOT NULL,
        SYMBOLS_COUNT   NUMBER(6, 0) NOT NULL,
        TOTAL_SIGNALS   NUMBER(8, 0) DEFAULT 0,
        TOTAL_ORDERS    NUMBER(8, 0) DEFAULT 0,
        TOTAL_TRADES    NUMBER(8, 0) DEFAULT 0,
        CREATED_AT      TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
        CONSTRAINT FK_RUN_CONFIG FOREIGN KEY (CONFIG_ID) REFERENCES STRATEGY_CONFIGS(CONFIG_ID)
    )';
    DBMS_OUTPUT.PUT_LINE('Table BACKTEST_RUNS created.');
EXCEPTION
    WHEN OTHERS THEN IF SQLCODE = -955 THEN NULL; ELSE RAISE; END IF;
END;
/

-- 3. BẢNG STRATEGY_SIGNALS: Tín hiệu và vùng hợp lưu phát hiện được
BEGIN
    EXECUTE IMMEDIATE '
    CREATE TABLE STRATEGY_SIGNALS (
        SIGNAL_ID       VARCHAR2(64) PRIMARY KEY,
        RUN_ID          VARCHAR2(64) NOT NULL,
        SYMBOL          VARCHAR2(20) NOT NULL,
        TRADE_DATE      DATE NOT NULL,
        BAR_INDEX       NUMBER(10, 0) NOT NULL,
        SIGNAL_TYPE     VARCHAR2(10) NOT NULL, -- BUY, SELL
        CONFLUENCE_LOW  NUMBER(15, 4) NOT NULL,
        CONFLUENCE_HIGH NUMBER(15, 4) NOT NULL,
        CONFLUENCE_MID  NUMBER(15, 4) NOT NULL,
        GANN_75_LEVEL   NUMBER(15, 4) NOT NULL,
        LIMIT_PRICE     NUMBER(15, 4) NOT NULL,
        STOP_LOSS       NUMBER(15, 4) NOT NULL,
        TAKE_PROFIT     NUMBER(15, 4) NOT NULL,
        RISK_REWARD     NUMBER(10, 2) NOT NULL,
        CREATED_AT      TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
        CONSTRAINT FK_SIG_RUN FOREIGN KEY (RUN_ID) REFERENCES BACKTEST_RUNS(RUN_ID) ON DELETE CASCADE
    )';
    DBMS_OUTPUT.PUT_LINE('Table STRATEGY_SIGNALS created.');
EXCEPTION
    WHEN OTHERS THEN IF SQLCODE = -955 THEN NULL; ELSE RAISE; END IF;
END;

-- SQLite migration for a SEPARATE Layer3 Phase4 sidecar DB. Never touch Layer1/2 DB.
-- OHLC and ratio stored as decimal strings; application uses decimal.Decimal.
PRAGMA foreign_keys=ON;
CREATE TABLE IF NOT EXISTS reversal_setup (
    setup_id TEXT NOT NULL PRIMARY KEY,
    ticker TEXT NOT NULL,
    timeframe TEXT NOT NULL,
    rule_version TEXT NOT NULL,
    config_hash TEXT NOT NULL,
    source_version TEXT NOT NULL,
    calendar_id TEXT NOT NULL,
    calendar_hash TEXT NOT NULL,
    calendar_verified INTEGER NOT NULL CHECK(calendar_verified IN (0,1)),
    calendar_source_verification TEXT NOT NULL CHECK(calendar_source_verification IN ('UNVERIFIED','VERIFIED')),
    context_structure_id_1 TEXT NOT NULL,
    context_structure_id_2 TEXT NOT NULL,
    context_available_at TEXT NOT NULL,
    context_age_bars INTEGER,
    context_age_coverage_complete INTEGER NOT NULL CHECK(context_age_coverage_complete IN (0,1)),
    red_candle_1_time TEXT NOT NULL,
    red_candle_1_open TEXT NOT NULL,
    red_candle_1_high TEXT NOT NULL,
    red_candle_1_low TEXT NOT NULL,
    red_candle_1_close TEXT NOT NULL,
    red_candle_2_time TEXT NOT NULL,
    red_candle_2_open TEXT NOT NULL,
    red_candle_2_high TEXT NOT NULL,
    red_candle_2_low TEXT NOT NULL,
    red_candle_2_close TEXT NOT NULL,
    red_candle_3_time TEXT NOT NULL,
    red_candle_3_open TEXT NOT NULL,
    red_candle_3_high TEXT NOT NULL,
    red_candle_3_low TEXT NOT NULL,
    red_candle_3_close TEXT NOT NULL,
    body_1 TEXT NOT NULL,
    total_wick_1 TEXT NOT NULL,
    body_3 TEXT NOT NULL,
    total_wick_3 TEXT NOT NULL,
    status TEXT NOT NULL CHECK(status IN ('WAITING_REVERSAL','FOUND','EXPIRED','INVALIDATED')),
    reversal_candle_time TEXT,
    reversal_candle_open TEXT,
    reversal_candle_high TEXT,
    reversal_candle_low TEXT,
    reversal_candle_close TEXT,
    reversal_body TEXT,
    body_ratio TEXT,
    setup_detected_at TEXT NOT NULL,
    available_at TEXT NOT NULL,
    resolved_at TEXT,
    reason_code TEXT NOT NULL,
    red_triplet_crosses_session INTEGER NOT NULL CHECK(red_triplet_crosses_session IN (0,1)),
    window_crosses_session INTEGER NOT NULL CHECK(window_crosses_session IN (0,1)),
    observed_window_crosses_session INTEGER NOT NULL CHECK(observed_window_crosses_session IN (0,1)),
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL,
    UNIQUE(ticker,timeframe,red_candle_1_time,red_candle_2_time,red_candle_3_time,rule_version)
);
CREATE INDEX IF NOT EXISTS idx_reversal_setup_status ON reversal_setup(rule_version,status,ticker);
CREATE INDEX IF NOT EXISTS idx_reversal_setup_available ON reversal_setup(available_at);
CREATE TABLE IF NOT EXISTS reversal_setup_event (
    event_id TEXT NOT NULL PRIMARY KEY,
    setup_id TEXT NOT NULL REFERENCES reversal_setup(setup_id) ON DELETE RESTRICT,
    event_type TEXT NOT NULL CHECK(event_type IN ('CREATED','REVERSAL_FOUND','EXPIRED','INVALIDATED','RECOMPUTED')),
    event_time TEXT NOT NULL,
    available_at TEXT NOT NULL,
    reason_code TEXT NOT NULL,
    event_payload TEXT NOT NULL CHECK(json_valid(event_payload)),
    rule_version TEXT NOT NULL,
    config_hash TEXT NOT NULL,
    created_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_reversal_setup_event_lookup ON reversal_setup_event(setup_id,available_at,event_type);

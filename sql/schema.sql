-- 1. BẢNG STOCK_SYMBOLS: Quản lý danh mục mã chứng khoán
BEGIN
    EXECUTE IMMEDIATE '
    CREATE TABLE STOCK_SYMBOLS (
        SYMBOL_ID       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        SYMBOL          VARCHAR2(20) NOT NULL,
        YAHOO_TICKER    VARCHAR2(25) NOT NULL,
        COMPANY_NAME    VARCHAR2(255),
        EXCHANGE        VARCHAR2(20) NOT NULL,
        SECURITY_TYPE   VARCHAR2(50) DEFAULT ''EQUITY'',
        STATUS          VARCHAR2(50) DEFAULT ''ACTIVE'',
        SOURCE          VARCHAR2(100) DEFAULT ''OFFICIAL_LIST'',
        FIRST_DATA_DATE DATE,
        LAST_DATA_DATE  DATE,
        LAST_SYNC_AT    TIMESTAMP,
        CREATED_AT      TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
        CONSTRAINT UQ_STOCK_SYMBOLS_SYMBOL UNIQUE (SYMBOL),
        CONSTRAINT UQ_STOCK_SYMBOLS_YF UNIQUE (YAHOO_TICKER)
    )';
    DBMS_OUTPUT.PUT_LINE('Table STOCK_SYMBOLS created successfully.');
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE = -955 THEN
            DBMS_OUTPUT.PUT_LINE('Table STOCK_SYMBOLS already exists.');
        ELSE
            RAISE;
        END IF;
END;
/

-- Chỉ mục cho sàn giao dịch và trạng thái
BEGIN
    EXECUTE IMMEDIATE 'CREATE INDEX IDX_SYMBOLS_EXCHANGE_STATUS ON STOCK_SYMBOLS (EXCHANGE, STATUS)';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE = -955 THEN NULL; ELSE RAISE; END IF;
